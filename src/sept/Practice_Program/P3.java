package sept.Practice_Program;

public class P3 {
    public static void main(String[] args) {
        double a = 34;
        double b = 10;
        System.out.printf("Sum of %f + %f = %f", a,b,a+b);
        System.out.println();
        System.out.printf("Substraction of %f - %f = %f", a,b,a-b);
        System.out.println();
        System.out.printf("Division of %f / %f = %f", a,b,a/b);
        System.out.println();
        System.out.printf("Multiplication of %f * %f = %f", a,b,a*b);
        System.out.println();
        System.out.printf("Modulos of %f (?) %f = %f", a,b,a%b);
        System.out.println();

    }

}

